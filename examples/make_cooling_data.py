"""Generate the synthetic cooling data set used in the documentation and tests.

The data imitate a temperature logger recording a cup of water cooling in a
room, following Newton's law of cooling::

    T(t) = T_room + (T_start - T_room) * exp(-t / tau)

Typical defects of real logger files are then added on purpose (see DEFECTS
below), so that every cleaning step of labcurve has something to do. The
random generator is seeded, which makes the file exactly reproducible:

    python examples/make_cooling_data.py
"""

from __future__ import annotations

from pathlib import Path

import numpy as np

T_START = 90.0  # degrees Celsius
T_ROOM = 22.0  # degrees Celsius
TAU = 600.0  # seconds
NOISE = 0.5  # standard deviation of the sensor noise, degrees Celsius
SEED = 20261009

#: Deliberate defects, as ``row index -> replacement text for the temperature``.
DEFECTS = {7: "", 23: "n/a", 31: "sensor error"}
#: Deliberate outliers, as ``row index -> offset in degrees Celsius``.
OUTLIERS = {15: 6.0, 44: -5.0}
#: Index of a row that is written twice.
DUPLICATED_ROW = 50

HEADER = """\
# Synthetic data: water cooling in a room (Newton's law of cooling).
# Generated by examples/make_cooling_data.py with a fixed random seed.
# True parameters: T_start = 90 C, T_room = 22 C, tau = 600 s, noise = 0.5 C.
time_s,temp_c,temp_err_c
"""


def build_rows() -> list[str]:
    """Return the CSV rows, including the deliberate defects."""
    rng = np.random.default_rng(SEED)
    time = np.arange(0.0, 3601.0, 60.0)
    temperature = T_ROOM + (T_START - T_ROOM) * np.exp(-time / TAU)
    temperature += rng.normal(0.0, NOISE, size=time.size)

    rows = []
    for index, (t, value) in enumerate(zip(time, temperature, strict=True)):
        text = DEFECTS.get(index, f"{value + OUTLIERS.get(index, 0.0):.2f}")
        row = f"{t:.0f},{text},{NOISE}"
        rows.append(row)
        if index == DUPLICATED_ROW:
            rows.append(row)
    return rows


def main() -> None:
    """Write ``cooling.csv`` next to this script."""
    target = Path(__file__).with_name("cooling.csv")
    target.write_text(HEADER + "\n".join(build_rows()) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {target}")


if __name__ == "__main__":
    main()
